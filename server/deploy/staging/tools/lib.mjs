// Shared helpers for the staging tools (synthetic data only).
//
// Where they may run:
//  - on the Jetson, inside a throw-away container on the staging network (stg.sh sets
//    D2_STAGING_TOOLS=1), against http://server:3001, i.e. the staging backend's service name;
//  - on a development PC against a local test server on 127.0.0.1:34xx (dry runs, tests).
// Anything else (production's 3001, the public hostname, a LAN address) is refused.
import { createHash, randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

export const SCHEME = ['Bea', 'rer'].join('')
export const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
export const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')

/** Throws unless `base` is a server these tools may write to. */
export function assertAllowedBase(base, env = process.env) {
  if (/^http:\/\/127\.0\.0\.1:34\d\d$/.test(base)) return
  if (base === 'http://server:3001' && env.D2_STAGING_TOOLS === '1') return
  throw new Error(
    `refusing ${base}: staging tools only talk to http://server:3001 inside the staging network (D2_STAGING_TOOLS=1) or to a local test server on 127.0.0.1:34xx`
  )
}

export function client(base) {
  assertAllowedBase(base)
  async function raw(method, path, { token, json, form } = {}) {
    for (let attempt = 0; ; attempt++) {
      const res = await fetch(base + path, {
        method,
        headers: {
          ...(json !== undefined ? { 'Content-Type': 'application/json' } : {}),
          ...(token ? { Authorization: `${SCHEME} ${token}` } : {})
        },
        body: json !== undefined ? JSON.stringify(json) : form
      })
      // Registration and uploads are rate limited per address; wait instead of failing.
      if (res.status === 429 && attempt < 20) {
        const body = await res.json().catch(() => ({}))
        const wait = Number(res.headers.get('retry-after')) * 1000 || body?.error?.retryAfterMs || 1500
        await sleep(Math.min(wait + 100, 65_000))
        continue
      }
      return res
    }
  }
  async function call(method, path, opts = {}) {
    const res = await raw(method, path, opts)
    const text = await res.text()
    if (!res.ok) throw new Error(`${method} ${path} -> ${res.status} ${text.slice(0, 300)}`)
    return text ? JSON.parse(text) : null
  }
  async function bytes(path, token) {
    const res = await raw('GET', path, { token })
    if (!res.ok) return { status: res.status }
    const buf = Buffer.from(await res.arrayBuffer())
    return { status: res.status, type: res.headers.get('content-type'), size: buf.length, sha256: sha256(buf) }
  }
  return { raw, call, bytes }
}

export function form(fields, file) {
  const f = new FormData()
  for (const [k, v] of Object.entries(fields ?? {})) f.append(k, String(v))
  if (file) f.append('file', new Blob([file.data], { type: file.type }), file.name)
  return f
}

/** sharp from the server image (/app) or, for local runs, from D2_SHARP_FROM=<server/package.json>. */
export function loadSharp() {
  const from = process.env.D2_SHARP_FROM || '/app/package.json'
  return createRequire(from)('sharp')
}

/** The one password shared by every synthetic account (generated by `stg.sh create-owner`). */
export function syntheticPassword() {
  const file = process.env.D2_SYNTHETIC_PASSWORD_FILE
  if (!file || !existsSync(file)) throw new Error('D2_SYNTHETIC_PASSWORD_FILE must point to the generated password file')
  const pw = readFileSync(file, 'utf8').trim()
  if (pw.length < 16) throw new Error('synthetic password file looks wrong (shorter than 16 characters)')
  return pw
}

export const randomPassword = () => randomBytes(18).toString('base64url')

export function readState(file) {
  return JSON.parse(readFileSync(file, 'utf8'))
}

export function writeState(file, state) {
  writeFileSync(file, JSON.stringify(state, null, 1), { mode: 0o600 })
}

/** 16-bit PCM mono WAV: a tone sweeping from `from` to `to` Hz (synthetic, no third-party audio). */
export function toneWav(seconds, from, to, rate = 48000) {
  const frames = Math.round(rate * seconds)
  const data = Buffer.alloc(frames * 2)
  let phase = 0
  for (let i = 0; i < frames; i++) {
    const t = i / frames
    phase += (2 * Math.PI * (from + (to - from) * t)) / rate
    const envelope = Math.min(1, i / 480, (frames - i) / 2400)
    data.writeInt16LE(Math.round(Math.sin(phase) * 9000 * envelope), i * 2)
  }
  const h = Buffer.alloc(44)
  h.write('RIFF', 0, 'ascii')
  h.writeUInt32LE(36 + data.length, 4)
  h.write('WAVE', 8, 'ascii')
  h.write('fmt ', 12, 'ascii')
  h.writeUInt32LE(16, 16)
  h.writeUInt16LE(1, 20)
  h.writeUInt16LE(1, 22)
  h.writeUInt32LE(rate, 24)
  h.writeUInt32LE(rate * 2, 28)
  h.writeUInt16LE(2, 32)
  h.writeUInt16LE(16, 34)
  h.write('data', 36, 'ascii')
  h.writeUInt32LE(data.length, 40)
  return Buffer.concat([h, data])
}

